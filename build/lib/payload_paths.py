#!/usr/bin/env python3
"""Write portable/paths.sh and portable/paths.cmd for an assembled folder.

  payload_paths.py DIST_ROOT

Reads desktop/resources/agent-payload/tools/facts.json (PM's installed-state
file: package -> store entry directory) and records every path the launchers
need, relative to DIST_ROOT. Prints VERSION.txt lines (desktop exe, tool versions).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

PAYLOAD = Path("desktop/resources/agent-payload")
# PM binary_rel for win32 (pm/packages.py): the directory that goes on PATH.
TOOL_DIRS = {"node": "", "npm": "", "uv": "", "ripgrep": "", "ffmpeg": "bin"}
SH_NAMES = {"node": "HP_NODE_DIR_REL", "npm": "HP_NPM_DIR_REL", "uv": "HP_UV_DIR_REL",
            "ripgrep": "HP_RG_DIR_REL", "ffmpeg": "HP_FFMPEG_DIR_REL"}


def main() -> None:
    root = Path(sys.argv[1]).resolve()
    payload = root / PAYLOAD
    facts = json.loads((payload / "tools/facts.json").read_text(encoding="utf-8-sig"))["packages"]

    def entry(name: str) -> Path | None:
        fact = facts.get(name)
        if not isinstance(fact, dict) or "entry" not in fact:
            return None
        return PAYLOAD / "tools" / fact["entry"]

    def rel(path: Path | None) -> str:
        return path.as_posix() if path else ""

    git = entry("git")
    python = entry("python")
    if git is None or not (root / git / "usr/bin/bash.exe").is_file():
        raise SystemExit("payload has no PortableGit (tools/facts.json: git)")
    if python is None or not (root / python / "python.exe").is_file():
        raise SystemExit("payload has no Python (tools/facts.json: python)")
    exes = sorted((root / "desktop").glob("*.exe"), key=lambda p: p.stat().st_size, reverse=True)
    if not exes:
        raise SystemExit("desktop/ has no executable")
    desktop_exe = exes[0].relative_to(root)  # Electron's main exe is by far the largest

    values = {
        "HP_PAYLOAD_REL": PAYLOAD.as_posix(),
        "HP_DESKTOP_EXE_REL": desktop_exe.as_posix(),
        "HP_GIT_REL": rel(git),
        "HP_PYTHON_EXE_REL": rel(python / "python.exe"),
    }
    for name, sub in TOOL_DIRS.items():
        base = entry(name)
        values[SH_NAMES[name]] = rel(base / sub if base and sub else base)

    sh = ["# Generated by build/lib/payload_paths.py; paths relative to the portable folder."]
    sh += [f"{key}='{value}'" for key, value in values.items()]
    (root / "portable/paths.sh").write_text("\n".join(sh) + "\n", encoding="utf-8", newline="\n")
    cmd = ["@rem Generated by build/lib/payload_paths.py; paths relative to the portable folder."]
    cmd += [f'@set "{key}={value.replace("/", chr(92))}"' for key, value in values.items()]
    (root / "portable/paths.cmd").write_text("\r\n".join(cmd) + "\r\n", encoding="ascii")

    # VERSION.txt lines: the desktop executable and every bundled tool version.
    print(f"desktop_exe={desktop_exe.name}")
    for name, fact in sorted(facts.items()):
        if isinstance(fact, dict) and "entry" in fact:
            print(f"tool.{name}={fact.get('version', '')}")


if __name__ == "__main__":
    main()
